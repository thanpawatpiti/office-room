'use strict';
const assert = require('node:assert/strict');
const { makeQuestion, answerQuestion, answerText, validateTasks, runnable } = require('../team-workflow');
const q = makeQuestion('codex', [{ id:'scope', question:'ทำที่ไหน?', options:[{label:'macOS'},{label:'Web'}] }, { id:'features', question:'ต้องการอะไร?', multiSelect:true, options:[{label:'คำถาม'},{label:'ประชุม'}] }]);
const a = { scope:{selected:['o1']}, features:{selected:['o1','o2'],text:'ภาษาไทย'} };
assert.throws(() => answerQuestion(q, {scope:{selected:['o1','o2']}}));
assert.equal(q.status, 'pending');
assert.equal(answerQuestion(q,a), true); assert.equal(answerQuestion(q,a), false);
assert.match(answerText(q), /macOS/); assert.match(answerText(q), /ภาษาไทย/);
assert.throws(() => answerQuestion(q,{...a,scope:{selected:['o2']}}));
assert.throws(() => makeQuestion('x',[{question:'x',options:[{label:'a'},{label:'a'}]}]));
const task = (id,owner,files,dependsOn=[]) => ({id,owner,files,dependsOn,assignment:id,reason:'distinct deliverable'});
const tasks = validateTasks([task('backend','codex',['/project/server.js']), task('native','claude',['/project/app']), task('review','claude',['/project/server.js'],['backend','native'])], ['/project'], ['codex','claude']);
assert.deepEqual(runnable(tasks).map(t=>t.id),['backend','native']);
tasks[0].status='waiting'; assert.deepEqual(runnable(tasks).map(t=>t.id),['native']);
tasks[1].status='done'; assert.equal(runnable(tasks).length,0);
tasks[0].status='done'; assert.deepEqual(runnable(tasks).map(t=>t.id),['review']);
assert.throws(()=>validateTasks([task('a','codex',['/project/a'],['b']),task('b','claude',['/project/b'],['a'])],['/project'],['codex','claude']));
assert.throws(()=>validateTasks([task('a','codex',['/project/../outside'])],['/project'],['codex']));
const conflict = validateTasks([task('a','codex',['/project/app']),task('b','claude',['/project/app/a.swift'])],['/project'],['codex','claude']);
assert.equal(runnable(conflict).length,1);
console.log('Structured answers, idempotency, task dependency cycles and exclusive scheduling passed');
