'use strict';
const assert = require('node:assert/strict');
const { claudeMembers, codexMembers } = require('../agent-tracker');
let m = {};
assert.equal(claudeMembers(m, {type:'stream_event',event:{type:'content_block_start',content_block:{type:'tool_use',name:'Agent',id:'a'}}}), true);
assert.equal(Object.keys(m).length, 1);
claudeMembers(m, {type:'assistant',message:{content:[{type:'tool_use',name:'Agent',id:'a'}]}});
assert.equal(Object.keys(m).length, 1);
claudeMembers(m, {type:'system',subtype:'task_started',tool_use_id:'a',task_id:'t',task_type:'local_agent'});
claudeMembers(m, {type:'user',message:{content:[{type:'tool_result',tool_use_id:'a'}]}});
assert.equal(Object.keys(m).length, 1, 'background task stays until completion');
claudeMembers(m, {type:'system',subtype:'task_notification',task_id:'t'});
assert.equal(Object.keys(m).length, 0);
claudeMembers(m, {type:'system',subtype:'task_started',tool_use_id:'b',task_type:'local_bash'});
assert.equal(Object.keys(m).length, 0, 'background shell is not an agent');
claudeMembers(m, {parent_tool_use_id:'a',type:'assistant',message:{content:[{type:'tool_use',name:'Agent',id:'nested'}]}});
assert.equal(Object.keys(m).length, 1, 'nested agent is counted');
claudeMembers(m, {parent_tool_use_id:'a',type:'user',message:{content:[{type:'tool_result',tool_use_id:'nested'}]}});
assert.equal(Object.keys(m).length, 0);
m = {};
codexMembers(m, {type:'collabAgentToolCall',tool:'spawnAgent',receiverThreadIds:['1','2'],agentsStates:{}});
assert.equal(Object.keys(m).length, 2);
codexMembers(m, {type:'collabAgentToolCall',tool:'wait',agentsStates:{'1':{status:'completed'},'2':{status:'running'}}});
assert.deepEqual(Object.keys(m), ['2']);
codexMembers(m, {type:'subAgentActivity',kind:'completed',agentThreadId:'2'});
assert.equal(Object.keys(m).length, 0);
codexMembers(m, {type:'subAgentActivity',kind:'started',agentThreadId:'3'});
codexMembers(m, {type:'collabAgentToolCall',tool:'closeAgent',status:'completed',receiverThreadIds:['3']});
assert.equal(Object.keys(m).length, 0);
console.log('Agent lifecycle tracking passed');
